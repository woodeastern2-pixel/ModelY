async def main():
    out = Path('artifacts/narration')
    out.mkdir(parents=True, exist_ok=True)
    (out / 'script.json').write_text(json.dumps(SCENES, ensure_ascii=False, indent=2))
    for code, title, text in SCENES:
        for attempt in range(3):
            try:
                await edge_tts.Communicate(text, 'ko-KR-SunHiNeural', rate='+8%').save(str(out / f'{code}.mp3'))
                print(code, title, flush=True)
                break
            except Exception:
                if attempt == 2: raise
                await asyncio.sleep(2)

if __name__ == '__main__':
    asyncio.run(main())
